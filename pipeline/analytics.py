"""Счётчик посещаемости: один рычаг, один идентификатор, один список хостов.

Владелец решил ставить GA4 (26.08.2026): «от неё будем отталкиваться». Решение
осознанное и оно стоит сайту его главного технического отличия — до сегодняшнего
дня страница делала ТРИ запроса и ни одного к чужому хосту, тогда как у
конкурентов их восемнадцать к пяти доменам. Взамен появляются данные, которых
Search Console не даёт: поведение внутри сайта, источники переходов, глубина
просмотра. У соседнего сайта фермы тот же счётчик показывает 51 пользователя за
неделю — то есть данные реальные, а не теоретические.

СОГЛАСИЕ. Политика приватности сайта обещает: посетителям из ЕЭЗ и
Великобритании выбор показывается ДО установки любой необязательной cookie.
Обещание выполняется без баннера — режимом согласия Google (Consent Mode v2) с
РЕГИОНАЛЬНЫМИ умолчаниями:

  * для ЕЭЗ, Великобритании и Швейцарии `analytics_storage` по умолчанию
    ЗАПРЕЩЁН. Счётчик работает без cookie: уходят обезличенные сигналы, из
    которых Google строит оценку, а идентификатор в браузере не сохраняется.
    Необязательных cookie не ставится ни одной — значит и спрашивать не о чем.
  * для остальных (наш рынок — США) `analytics_storage` разрешён, счётчик
    работает обычным образом.

Это честнее баннера: баннер спрашивает разрешение на то, что уже решено за
пользователя по умолчанию, а здесь для защищённых регионов умолчание само по
себе строгое.

ЧТО ЕЩЁ ТЯНЕТ ЗА СОБОЙ ВКЛЮЧЕНИЕ:
  1. Content-Security-Policy расширяется на два хоста Google — иначе браузер
     молча не исполнит скрипт, и причина будет неочевидной.
  2. Гейт внешних запросов должен ЗНАТЬ про эти хосты, иначе сборка краснеет.
  3. Страница приватности обязана описывать происходящее ДО того, как тег
     уедет в продакшн, а не после. Это записано на самой странице как
     обещание, и гейт проверяет его в обе стороны.
"""
from __future__ import annotations

# Ресурс «GS Pay Tables» в аккаунте BiLingoPlus, поток «GS Pay Tables — web».
# Часовой пояс ресурса — нью-йоркский: рабочий день федерального служащего
# идёт по восточному времени, и границы суток в отчётах должны совпадать с ним.
MEASUREMENT_ID = "G-7744PF99S1"

ANALYTICS_LIVE = True

# Хосты, которые появляются в сети при включённом счётчике. Список нужен и
# гейту внешних запросов, и политике безопасности — поэтому он один.
HOSTS = ("www.googletagmanager.com", "www.google-analytics.com")

# Регионы, где по умолчанию запрещено хранение: ЕЭЗ + Великобритания +
# Швейцария. Коды в формате, который принимает Consent Mode.
STRICT_REGIONS = (
    "AT", "BE", "BG", "HR", "CY", "CZ", "DK", "EE", "FI", "FR", "DE", "GR",
    "HU", "IS", "IE", "IT", "LV", "LI", "LT", "LU", "MT", "NL", "NO", "PL",
    "PT", "RO", "SK", "SI", "ES", "SE", "GB", "CH",
)


def head_tag() -> str:
    """Разметка счётчика для головы документа. Пусто, если он выключен."""
    if not ANALYTICS_LIVE:
        return ""
    regions = ",".join(f"'{c}'" for c in STRICT_REGIONS)
    # Порядок важен: умолчания согласия объявляются ДО загрузки самого тега,
    # иначе первый запрос уйдёт по разрешающему умолчанию.
    return (
        "<script>window.dataLayer=window.dataLayer||[];"
        "function gtag(){dataLayer.push(arguments)}"
        "gtag('consent','default',{'ad_storage':'denied',"
        "'ad_user_data':'denied','ad_personalization':'denied',"
        "'analytics_storage':'denied','region':[" + regions + "]});"
        "gtag('consent','default',{'ad_storage':'denied',"
        "'ad_user_data':'denied','ad_personalization':'denied',"
        "'analytics_storage':'granted'});"
        "gtag('js',new Date());"
        "gtag('config','" + MEASUREMENT_ID + "');</script>"
        '<script async src="https://www.googletagmanager.com/gtag/js?id='
        + MEASUREMENT_ID + '"></script>'
    )


def csp_sources() -> str:
    """Добавка к политике безопасности. Пусто, если счётчик выключен."""
    if not ANALYTICS_LIVE:
        return ""
    return " https://www.googletagmanager.com https://www.google-analytics.com"
