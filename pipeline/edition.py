"""Год издания — одна константа, вычисляемая по календарю.

До 2026-08-26 год стоял литералом в шести местах: `--year` по умолчанию 2026
в fetch.py, parse.py и localities.py, и чтение `paytables-2026.json` по имени
в rpp.py, zips.py и render.py. Ежемесячная пересборка по расписанию существует
ровно ради двух недель конца декабря, когда OPM публикует таблицы следующего
года, — но с зашитым годом она собирала бы 2026-й вечно.

Хуже того, гейт свежести пропускал это по построению: он сверял скачанный файл
с ЗАПРОШЕННЫМ годом, а запрашивали всегда один и тот же. В январе 2027 запрос
ушёл бы за 2026-й, вернулся бы 2026-й, гейт стал бы зелёным, и сайт молча
остался бы прошлогодним. Это тот же класс, что «гейт читает собранное, а не
отданное»: проверка сверяла результат с собственным вводом, а не с внешней
истиной.

Что считаем годом издания: КАЛЕНДАРНЫЙ год. Ставки General Schedule действуют
с первого расчётного периода января и до конца года, поэтому «таблицы, которые
действуют сейчас» — это таблицы текущего календарного года.

Год можно задать руками: переменная окружения GS_YEAR или --year у скриптов.
Это нужно ровно в одном случае — OPM задержал публикацию, и январская сборка
должна пока остаться на прошлогодних таблицах. Тогда это осознанное решение
оператора, записанное в команде запуска, а не молчаливый откат.
"""
from __future__ import annotations

import os
from datetime import date


def target_year(today: date | None = None) -> int:
    """Год, таблицы которого должны быть на сайте."""
    env = os.environ.get("GS_YEAR", "").strip()
    if env:
        if not env.isdigit() or not (2000 <= int(env) <= 2100):
            raise SystemExit(f"GS_YEAR={env!r} — это не похоже на год")
        return int(env)
    return (today or date.today()).year


YEAR = target_year()
