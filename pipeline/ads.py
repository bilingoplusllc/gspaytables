"""Рекламные места и ОДИН переключатель на все точки вставки.

RELEASE.md утверждал: «Места существуют, высоты зарезервированы, включаются
классом `.on`». Первая половина была правдой, вторая — нет: класс `.on` не
выставлялся нигде. Семь точек вставки в четырёх файлах писали разметку
литералом, а `design.py` держал `.ad-slot{display:none}` и `.ad-slot.on{…}`.
То есть переключателя не существовало, и в день подключения сети правку
пришлось бы делать в семи местах, ничего при этом не забыв.

Документированный, но несуществующий рычаг хуже отсутствующего: на него
рассчитывают.

Здесь он один. `ADS_LIVE = True` включает показ во всех местах разом. Гейт в
render.py не даёт выложить сайт с включённой рекламой без `ads.txt` — файл
нужен всем трём сетям в день подключения, и забыть его легче всего.
"""
from __future__ import annotations

# Реклама не подключается, пока не принято решение по рекламному аккаунту.
# Места при этом существуют и занимают высоту: включение не должно сдвигать
# вёрстку — сдвиг после загрузки штрафуется поисковиком и раздражает читателя.
ADS_LIVE = False

# В ДЕНЬ ВКЛЮЧЕНИЯ нужны ещё две вещи, помимо этой строки:
#   1. ads.txt в корне — гейт в render.py не даст выложить без него;
#   2. расширить Content-Security-Policy в render.py: сеть грузит скрипты и
#      картинки со СВОИХ хостов, а сейчас политика разрешает только свой домен.
#      Без этого реклама просто не покажется, и причина будет неочевидной —
#      разметка на месте, а браузер молча её не исполняет.

# Форматы мест. Ключ — суффикс класса, значение — зачем место существует.
KINDS = {
    "band": "полоса на всю ширину колонки, между разделами",
    "rail": "узкое место на поле, рядом с таблицей",
}


def slot(kind: str) -> str:
    """Разметка одного рекламного места."""
    if kind not in KINDS:
        raise ValueError(f"неизвестный формат места: {kind!r}")
    on = " on" if ADS_LIVE else ""
    return f'<div class="ad-slot ad-{kind}{on}">Advertisement</div>'
